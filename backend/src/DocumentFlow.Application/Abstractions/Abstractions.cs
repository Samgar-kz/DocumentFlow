using DocumentFlow.Domain.Audit;
using DocumentFlow.Domain.Common;
using DocumentFlow.Domain.Documents;
using DocumentFlow.Domain.Notifications;
using DocumentFlow.Domain.Users;
using Microsoft.EntityFrameworkCore;

namespace DocumentFlow.Application.Abstractions;

/// <summary>Unit of work exposed to the application layer. Implemented by the EF Core context.</summary>
public interface IAppDbContext
{
    DbSet<User> Users { get; }

    DbSet<RefreshToken> RefreshTokens { get; }

    DbSet<Document> Documents { get; }

    DbSet<DocumentVersion> DocumentVersions { get; }

    DbSet<ApprovalStep> ApprovalSteps { get; }

    DbSet<AuditEntry> AuditEntries { get; }

    DbSet<Notification> Notifications { get; }

    Task<int> SaveChangesAsync(CancellationToken cancellationToken = default);
}

/// <summary>
/// Reacts to domain events while changes are being saved. Handlers only add entities to the
/// context, so their output is committed atomically with the change that caused it.
/// </summary>
public interface IDomainEventHandler
{
    void Handle(IDomainEvent domainEvent, IAppDbContext db);
}

/// <summary>Binary storage for uploaded files. Keys are generated by the application, never by users.</summary>
public interface IFileStorage
{
    Task SaveAsync(string key, Stream content, CancellationToken cancellationToken);

    Task<Stream> OpenReadAsync(string key, CancellationToken cancellationToken);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

public interface ICurrentUser
{
    Guid Id { get; }

    bool IsAdmin { get; }
}

public interface IPasswordHasher
{
    string Hash(User user, string password);

    PasswordCheck Verify(User user, string password);
}

public enum PasswordCheck
{
    Failed,
    Success,
    SuccessRehashNeeded,
}

public interface ITokenService
{
    AccessToken CreateAccessToken(User user);

    IssuedRefreshToken CreateRefreshToken();

    string HashRefreshToken(string refreshToken);
}

public sealed record AccessToken(string Token, DateTimeOffset ExpiresAt);

public sealed record IssuedRefreshToken(string Token, string Hash, DateTimeOffset ExpiresAt);
